def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:
        data = json.load(response)
    codes: dict[str, str] = {}
    for entry in data:
        emoji = "".join(chr(int(code, 16)) for code in entry["unified"].split("-"))
        for name in entry["short_names"]:
            codes[name] = emoji
    lines = []
    for name in sorted(codes):
        lines.append(f"    {json.dumps(name, ensure_ascii=False)}: {json.dumps(codes[name], ensure_ascii=False)},\n")
    OUT.write_text(HEADER + "".join(lines) + "}\n", encoding="utf-8")
    print(f"{len(codes)} names -> {OUT}")


if __name__ == "__main__":
    main()
